"""0701 钓台本体与顶棚 — 三张硬件爆炸图（hand3d 管线）
0701-1 预制墩木框钓台平台 / 0701-2 竹瓦单坡顶棚 / 0701-3 缓坡踏步与竹扶手

坐标约定（整个区域 07 共用）：
  X 沿河岸（0～2500 = 台面 2.5m 宽），Y 由岸指向河（0 = 靠坡一侧，2200 = 临河一侧），
  Z=0 是台面上表面。钓台落在缓坡坡脚的岸上，不伸进水面。
"""
import sys, os, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
from hand3d import box, cyl
from partdraw import draw
from p56util import (merge, rot, mv, prism, path_tube, seg_tube, arc_pts, cone,
                     audit, patch, gravel, cut_soil, tuft, capped_cyl, disc)

PW, PD = 2500.0, 2200.0          # 台面 2.5×2.2m


def rotx(p, ang, c):
    a = math.radians(ang); y = p[1] - c[1]; z = p[2] - c[2]
    return (p[0], c[1] + y * math.cos(a) - z * math.sin(a),
            c[2] + y * math.sin(a) + z * math.cos(a))


# ---------------------------------------------------------------- 0701-1
def fig1():
    """沿 Z 向四层爆炸：碎石垫层+墩 / 木框龙骨 / 面板 / 挡水条。"""
    S = []
    # 岸土（坡脚地面，只给比平台大一圈的一小块）
    S.append(cut_soil(3100, 2800, 400, (-300, -300, -1900), "坡脚岸土"))

    # ① 预制混凝土墩 ×6 + 40cm 碎石垫层 + 镀锌柱脚
    PX = (150, 1100, 2050)
    PY = (150, 1750)
    for x in PX:
        for y in PY:
            S.append(gravel((x - 110, y - 110, -1500), 520, 520, 12, 44, 44, "碎石垫层"))
            S.append(box((300, 300, 400), (x, y, -1250), "预制混凝土墩"))
            S.append(box((200, 200, 14), (x + 50, y + 50, -850), "镀锌柱脚"))
            S.append(cyl(9, 110, "z", (x + 150, y + 150, -836), 8, "地脚螺栓"))

    # ② 防腐松木框龙骨 90×45，间距 400
    ZJ = -420
    jo = [box((PW, 45, 90), (0, 0, ZJ), "木框龙骨"),
          box((PW, 45, 90), (0, PD - 45, ZJ), "木框龙骨")]
    for i in range(7):
        jo.append(box((45, PD, 90), (i * 400, 0, ZJ), "木框龙骨"))
    jo.append(box((45, PD, 90), (PW - 45, 0, ZJ), "木框龙骨"))
    S.append(merge(jo, "防腐松木框龙骨"))

    # ③ 防腐木面板 2.5×2.2m，板缝留 5mm
    n = 14
    pitch = PD / n
    dk = [box((PW, pitch - 5, 30), (0, i * pitch, 0), "防腐木面板") for i in range(n)]
    S.append(merge(dk, "防腐木面板"))

    # ④ 临河侧 10cm 木挡水条
    S.append(box((PW, 45, 100), (0, PD - 45, 400), "木挡水条"))

    items = [("①", "预制混凝土墩 ×6，40cm 碎石垫层", (300, 150, -1050)),
             ("②", "防腐松木框龙骨 90×45，间距 400", (1200, 0, ZJ + 45)),
             ("③", "防腐木面板 2.5×2.2m，板缝留 5mm", (700, 620, 30)),
             ("④", "临河侧 10cm 木挡水条防滚落", (1250, PD - 45, 450)),
             ("⑤", "不打桩不下水，墩自重托住整台", (2200, 1750, -1420))]
    audit(items, S, -62, 20)
    print("saved", draw("0701-1", "预制墩木框钓台平台", items, S,
                        note="坡脚临河岸上 2.5×2.2m、5.5㎡ 的小平台，不伸进水面；六墩下各挖 40cm 夯碎石垫层",
                        sig="设想 · 0701", az=-62, el=20, fov=27))


