def fig2():
    """单坡顶棚：柱 / 梁 / 檩 / 竹瓦 逐层向上拉开，檐口挂雨链。"""
    S = []
    dk = box((PW, PD, 30), (0, 0, -30), "钓台台面"); dk.shade = False
    S.append(dk)

    # ① 杉木柱 Φ120 ×4：高侧（靠坡）2.3m，低侧（临河）2.0m
    CX = (210, 2290)
    CH = {160: 2300, 2040: 2000}
    for x in CX:
        for y in (160, 2040):
            S.append(capped_cyl(60, CH[y], "z", (x, y, 0), 16, "杉木柱"))

    # ② 横梁（拉高 400）
    EB = 400
    S.append(box((2200, 130, 120), (150, 95, 2300 + EB), "横梁"))
    S.append(box((2200, 130, 120), (150, 1975, 2000 + EB), "横梁"))

    # ③ 檩条：铺在 2420→2120 的坡线上（拉高 840）
    EP = 840
    ANG = math.degrees(math.atan2(300.0, 1880.0))      # 单坡，2.2×2m 不超出台面
    for i in range(5):
        y = 160 + i * 470
        z = 2420 - i * 75
        S.append(box((2380, 80, 80), (60, y - 40, z + EP), "檩条"))

    # ④ 竹瓦：对半剖开一仰一覆扣合（在水平坐标里排好再转到坡面，最后整体抬高）
    ET = 1360
    tiles = []
    for i in range(12):
        x = 160 + i * 185
        tiles.append(cyl(82, 1880, "y", (x, 160, 2420), 10, "覆瓦"))
        tiles.append(cyl(82, 1880, "y", (x + 92, 160, 2338), 10, "仰瓦"))
    roof = rot(merge(tiles, "竹瓦"), -ANG, "x", (0, 160, 2420))
    S.append(mv(roof, (0, 0, ET)))

    # 檐口铜雨链：从竹瓦低边（临河一侧）檐口外挂下来
    eav = rotx((40, 2030, 2330), -ANG, (0, 160, 2420))
    eav = (eav[0], eav[1] + 260, eav[2] + ET)
    links = []
    for k in range(8):
        z = eav[2] - 90 - k * 122
        pl = "xz" if k % 2 == 0 else "yz"
        links.append(path_tube(arc_pts((eav[0], eav[1], z), 58, 0, 360, 11, pl), 9, 6, "铜雨链"))
    S.append(merge(links, "铜雨链"))

    a4 = rotx((1060, 1900, 2502), -ANG, (0, 160, 2420))
    items = [("①", "杉木柱 Φ120 ×4，高 2.3m 低 2.0m", (189, 2092, 1300)),
             ("②", "柱顶横梁，屋面 2.2×2m 不超出台面", (2350, 2040, 2460)),
             ("③", "梁上钉檩条，坡向河一侧压低", (75, 1550, 2195 + EP + 40)),
             ("④", "竹瓦对半剖开一仰一覆扣合", (a4[0], a4[1], a4[2] + ET)),
             ("⑤", "檐口铜雨链一串，兼做排水与声景", (eav[0] + 58, eav[1], eav[2] - 578))]
    audit(items, S, 112, 20)
    print("saved", draw("0701-2", "竹瓦单坡顶棚", items, S,
                        note="顶棚 2.2×2.0m 压在 2.5×2.2m 台面范围内，坡向河一侧低，雨水落到台外岸边碎石上",
                        sig="设想 · 0701", az=112, el=20, fov=27))


