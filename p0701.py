def fig3():
    """6m 缓坡上的 12 级踏步：抽一级把木框和碎石填料拉开。"""
    S = []
    dz = 125.0                                   # 每级升高
    ANG = math.degrees(math.atan2(11 * dz, 5500.0))

    def zs(y):                                   # 坡面标高
        return 125.0 + (-200.0 - y) * dz / 500.0

    # 缓坡薄斜板（示意，不排线）
    sl = box((2600, 6500, 110), (-700, -6500, -110), "缓坡")
    sl = rot(sl, -ANG, "x", (0, -200, 40)); sl.shade = False
    S.append(sl)
    # 坡脚的钓台台面一角（背景）
    dk = box((2500, 700, 30), (-300, -200, 95), "钓台台面"); dk.shade = False
    S.append(dk)

    EXP = 5                                      # 被拉开示意的那一级
    for i in range(12):
        y, z = -200.0 - i * 500.0, 125.0 + i * dz
        up = 900 if i == EXP else 0
        fr = [box((1200, 45, 110), (0, y - 300, z - 110 + up), "踏步木框"),
              box((1200, 45, 110), (0, y - 45, z - 110 + up), "踏步木框"),
              box((45, 255, 110), (0, y - 300, z - 110 + up), "踏步木框"),
              box((45, 255, 110), (1155, y - 300, z - 110 + up), "踏步木框")]
        S.append(merge(fr, "踏步木框 90×45"))
        gz = z - 105 + (430 if i == EXP else 0)
        if i in (EXP, EXP - 3):
            S.append(gravel((50, y - 290, gz), 1090, 240, 15, 36, 66, "碎石夯实填料"))
        else:
            S.append(box((1110, 235, 100), (45, y - 290, gz), "碎石夯实填料"))

    # 单侧扶手：防腐木柱 + Φ60 去皮毛竹
    for y in (-900.0, -2600.0, -4300.0):
        S.append(box((90, 90, 950), (1290, y - 45, zs(y) - 200), "防腐木柱"))
    S.append(seg_tube((1335, -500, zs(-500) + 750), (1335, -5000, zs(-5000) + 750),
                      30, 12, "Φ60 去皮毛竹扶手"))

    # 踏步两侧留白：菖蒲与芦苇自己长过来
    for y in (-1100, -2900, -4700):
        S.append(tuft((-360, y, zs(y) - 60), 700, 230, 5, 15, "菖蒲芦苇"))
    for y in (-1900, -3900):
        S.append(tuft((1730, y, zs(y) - 60), 640, 220, 5, 15, "菖蒲芦苇"))

    ye, ze = -200.0 - EXP * 500.0, 125.0 + EXP * dz
    items = [("①", "缓坡 6m，踏步约 12 级，踏面 30cm", (600, -1720, 545)),
             ("②", "木框 90×45 钉成，与坡面齐平", (600, ye - 255, ze + 845)),
             ("③", "框内填碎石夯实，雨天不打滑", (600, ye - 170, ze + 390)),
             ("④", "单侧扶手 75cm，Φ60 去皮毛竹", (1335, -3200, zs(-3200) + 780)),
             ("⑤", "两侧留白，菖蒲芦苇自然长过来", (-360, -2900, zs(-2900) + 170))]
    audit(items, S, 62, 24)
    print("saved", draw("0701-3", "缓坡踏步与竹扶手", items, S,
                        note="从庭院南端出来过 2m 过道、下 6m 缓坡到坡脚钓台；踏步从北边坡上下来，两侧不种花",
                        sig="设想 · 0701", az=62, el=24, fov=27))


if __name__ == "__main__":
    fig1(); fig2(); fig3()
