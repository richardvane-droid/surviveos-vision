def fig2():
    S = []
    beam = box((300, 190, 140), (-150, -95, 2190), "梁底"); beam.shade = False
    S.append(beam)

    u = (0.0, -0.92, -0.39)                  # 爆炸方向：顺着掠射光线往外下方
    ST = 180
    def P(k, dx=0, dy=0, dz=0):
        return (dx, u[1] * ST * k + dy, 2190 + u[2] * ST * k + dz)

    # 1 可旋转梁底安装座
    x, y, z = P(1)
    S += [cyl(62, 26, "z", (x, y, z), 18, "梁底安装座"),
          cyl(26, 22, "z", (x, y, z - 22), 12, "转轴")]
    # 2 0-10V 恒流驱动器
    x, y, z = P(2)
    S += [box((150, 62, 42), (x - 75, y - 31, z), "恒流驱动器"),
          box((36, 12, 16), (x - 18, y - 43, z + 13), "0-10V 端子")]
    # 3 云台俯仰关节
    x, y, z = P(3)
    S += [box((104, 22, 18), (x - 52, y - 11, z + 78), "关节底板"),
          box((14, 56, 78), (x - 50, y - 28, z), "云台耳板"),
          box((14, 56, 78), (x + 36, y - 28, z), "云台耳板"),
          cyl(12, 100, "x", (x - 50, y, z + 28), 12, "俯仰轴")]
    # 4 COB 灯体 + 散热鳍
    x, y, z = P(4)
    S += [cyl(48, 88, "z", (x, y, z), 20, "COB 灯体")]
    for i in range(4):
        S.append(cyl(61, 8, "z", (x, y, z + 16 + i * 18), 20, "散热鳍"))
    S.append(cyl(31, 10, "z", (x, y, z - 10), 16, "COB 灯珠"))
    # 5 蜂窝防眩罩
    x, y, z = P(5)
    S.append(cyl(48, 44, "z", (x, y, z), 20, "蜂窝防眩罩"))
    hc = []
    for i in range(6):
        a = i * math.pi / 3
        hc.append(cyl(12, 38, "z", (x + 25 * math.cos(a), y + 25 * math.sin(a), z + 3), 6, "蜂窝"))
    hc.append(cyl(12, 38, "z", (x, y, z + 3), 6, "蜂窝"))
    S.append(merge(hc, "蜂窝格"))
    # 6 毫米波存在传感器小板
    x, y, z = P(6)
    S += [box((56, 38, 10), (x - 28, y - 19, z), "毫米波传感器"),
          cyl(3.5, 26, "z", (x + 18, y, z + 10), 8, "天线")]

    # 台面一角 / 卡 / 三倍放大压片（接在光路末端，实际在台面高 900）
    bx, by, bz = P(7.9)
    S.append(box((330, 230, 26), (bx - 165, by - 115, bz), "台面一角"))
    S.append(box((CW, CH, CT), (bx - 43, by - 62, bz + 26), "PSK 卡"))
    ZM = bz + 26 + CT + 25                   # 翻下时距卡面 25mm
    fr = [box((180, 16, 18), (bx - 90, by - 60, ZM), "压片框"),
          box((180, 16, 18), (bx - 90, by + 44, ZM), "压片框"),
          box((16, 120, 18), (bx - 90, by - 60, ZM), "压片框"),
          box((16, 120, 18), (bx + 74, by - 60, ZM), "压片框"),
          box((164, 104, 5), (bx - 82, by - 52, ZM + 6), "放大镜片")]
    S.append(merge(fr, "三倍放大压片"))
    S += [box((24, 130, 16), (bx - 12, by + 60, ZM + 1), "翻转臂"),
          cyl(15, 36, "x", (bx - 24, by + 180, ZM + 8), 12, "铰链")]

    items = [("①", "COB 灯体 3000K Ra≥95，12W 带散热鳍", P(4, dz=44)),
             ("②", "蜂窝防眩罩，15° 窄光束", P(5, dx=48, dz=22)),
             ("③", "云台俯仰 ±45°，0-10V 两秒渐亮", P(3, dx=43, dz=40)),
             ("④", "三倍放大压片翻下，距卡面约 25mm", (bx - 82, by - 52, ZM + 10)),
             ("⑤", "毫米波存在传感器，人近才亮", P(6, dx=-28, dz=5))]
    audit(items, S, -26, 18)
    p = draw("0101-2", "掠射射灯与放大压片", items, S,
             note="灯装在北墙梁底 2400、卡在台面 900：光几乎贴着托盘掠过去，入射角压到 15~25°，刻痕才有影子",
             sig="设想 · 0101", az=-26, el=18, fov=27)
    print("saved", p)


fig1()
fig2()
