"""0101 PSK 主产品展示 — 两张硬件爆炸图（hand3d 管线）
0101-1 胡桃木展台与黑胡桃托盘 / 0101-2 掠射射灯与放大压片
"""
import sys, os, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hand3d import box, cyl
from props import wall
from partdraw import draw
from p01util import merge, rot, prism, jar, screw, audit

CW, CH, CT = 85.6, 54.0, 2.4          # 卡片式 PSK：信用卡大小


# ---------------------------------------------------------------- 0101-1
def fig1():
    S = []
    S.append(wall(1600, 660, 80, (-120, 0, 500)))          # 只给够用的一块北墙

    # ① 手刨胡桃木托架 ×2（三角形，竖边咬墙）+ 膨胀螺栓
    br = []
    for x0 in (150, 1155):
        br.append(prism([(-320, 260), (0, 260), (0, 0)], 45, "x", (x0, 0, 560), "胡桃木托架"))
        for zz in (620, 780):
            br += screw((x0 + 22, -30, zz), 6, 105, "y", "膨胀螺栓")
    S += br

    # ② 薄抽屉层（历代原型卡）
    ZD = 1020
    S.append(box((1350, 330, 70), (0, -330, ZD), "薄抽屉"))
    S.append(box((1370, 22, 92), (-10, -352, ZD - 11), "抽屉面板"))
    S.append(cyl(8, 120, "x", (615, -366, ZD + 35), 10, "拉手"))

    # ③ 台面：135×35cm，前低后高倾斜 12°
    ZT = 1330
    top = box((1350, 350, 26), (0, -350, ZT), "台面")
    S.append(rot(top, 12, "x", (675, -175, ZT + 13)))

    # 黄铜铭牌 40×18，爆炸到台面前沿外
    S.append(box((40, 18, 3), (1060, -420, ZT + 40), "黄铜铭牌"))

    # ④ 黑胡桃托盘 30×20cm：左卡位 / 右小件爆炸位
    ZY = 1600
    tr = [box((300, 200, 13), (525, -275, ZY), "托盘")]
    tr += [box((300, 10, 17), (525, -275, ZY + 13), "盘沿"),
           box((300, 10, 17), (525, -85, ZY + 13), "盘沿"),
           box((10, 200, 17), (525, -275, ZY + 13), "盘沿"),
           box((10, 200, 17), (815, -275, ZY + 13), "盘沿"),
           box((8, 200, 15), (671, -275, ZY + 13), "中隔")]
    S.append(merge(tr, "黑胡桃托盘"))

    # ⑤ 卡片式 PSK 85.6×54 + 右半十来件小件
    ZC = ZY + 165
    S.append(box((CW, CH, CT), (555, -245, ZC), "PSK 卡"))
    tiny = [cyl(3.5, 52, "x", (695, -130, ZC + 4), 8, "打火棒"),
            box((40, 12, 2), (695, -172, ZC), "刀片"),
            cyl(10, 8, "z", (775, -150, ZC), 12, "鱼线卷"),
            cyl(1.6, 34, "x", (695, -205, ZC + 2), 6, "别针"),
            cyl(7, 4, "z", (752, -205, ZC), 10, "药片"),
            cyl(7, 4, "z", (774, -205, ZC), 10, "药片"),
            box((20, 11, 3), (695, -240, ZC), "缝针盒"),
            box((26, 16, 2), (732, -248, ZC), "铝箔"),
            cyl(5, 20, "z", (792, -240, ZC), 10, "火石")]
    S.append(merge(tiny, "十来件小件"))

    def rp(q, ang=12, c=(675, -175, ZT + 13)):
        a = math.radians(ang); yy, zz = q[1] - c[1], q[2] - c[2]
        return (q[0], c[1] + yy * math.cos(a) - zz * math.sin(a), c[2] + yy * math.sin(a) + zz * math.cos(a))

    items = [("①", "手刨胡桃木托架 ×2，膨胀螺栓咬墙", (172, -160, 745)),
             ("②", "薄抽屉一层，收历代原型卡", (300, -352, ZD + 35)),
             ("③", "台面 135×35cm，前低后高倾斜 12°", rp((1010, -245, ZT + 26))),
             ("④", "黑胡桃托盘 30×20：左卡位 右小件", (525, -180, ZY + 20)),
             ("⑤", "卡片式 PSK 85.6×54，毛毡留 18 指槽", (598, -218, ZC + 3))]
    audit(items, S, -62, 22)
    p = draw("0101-1", "胡桃木展台与黑胡桃托盘", items, S,
             note="北墙中段偏东、九宫格正下方；挂墙悬挑不落地，台面高 900 与西侧吧台齐平",
             sig="设想 · 0101", az=-62, el=22, fov=27)
    print("saved", p)


