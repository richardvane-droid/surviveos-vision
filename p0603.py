def cutaway_cyl(pos, r, h, t=16, a0=-20.0, a1=200.0, seg=16, axis="z", name="筒"):
    """剖开小半边的立式圆筒：只画 a0→a1 那段壁 + 筒底，正面敞开好看内部。"""
    x, y, z = pos
    th = np.radians(np.linspace(a0, a1, seg + 1))
    ro, ri = r, r - t
    F, E = [], []

    def ring(rad, zz):
        return [np.array([x + rad * math.cos(a), y + rad * math.sin(a), zz]) for a in th]
    o0, o1, i0, i1 = ring(ro, z), ring(ro, z + h), ring(ri, z), ring(ri, z + h)
    for k in range(seg):
        F += [[o0[k], o0[k + 1], o1[k + 1], o1[k]], [i1[k], i1[k + 1], i0[k + 1], i0[k]],
              [o1[k], o1[k + 1], i1[k + 1], i1[k]]]
        E += [(o0[k], o0[k + 1]), (o1[k], o1[k + 1]), (i1[k], i1[k + 1])]
    for k in (0, seg):
        F.append([o0[k], o1[k], i1[k], i0[k]])
        E += [(o0[k], o1[k]), (i0[k], i1[k]), (o1[k], i1[k]), (o0[k], i0[k])]
    return merge([Solid(F, E, name), cyl(ro, t, "z", (x, y, z), 20, name + "底")], name)


