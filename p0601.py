    # ① 沟宽 30cm 深 20cm
    S.append(box((LX, 300, 160), (0, -150, -420), "沟底原土"))
    # ② 底铺防草布，沿沟底和两壁翻上来
    S.append(box((LX, 300, 8), (0, -150, -260), "防草布"))
    S.append(box((900, 8, 240), (0, -150, -260), "防草布"))
    S.append(box((LX, 8, 240), (0, 142, -260), "防草布"))
    # ③ 粗砾垫层 10cm
    S.append(box((LX, 284, 100), (0, -142, -252), "10cm 粗砾垫层"))
    # ④ 面层 3~8cm 河卵石
    S.append(box((LX, 284, 60), (0, -142, -152), "河卵石面层"))
    S.append(gravel((0, -140, -96), LX, 280, 40, 46, 42, "河卵石"))

    # 草地一侧：混播草
    S.append(grass_row((240, 620, 0), (2560, 620, 0), 6, 660, 200, "细叶芒"))
    S.append(grass_row((500, 1120, 0), (2300, 1120, 0), 4, 460, 160, "狼尾草"))

