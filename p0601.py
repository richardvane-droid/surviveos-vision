def fig1():
    """阶梯式剖开的植床：每层往后收一截，露出上一层的做法。"""
    S = []
    LX = 2400.0                      # 沿长条截取 2.4m
    # ① 排水层：原土掺三成粗砂，翻深 30cm
    S.append(cut_soil(LX, 1200, 300, (0, -560, -600), "排水层"))
    # 下层种植土
    S.append(cut_soil(LX, 1040, 130, (0, -400, -300), "下层种植土"))
    # ② 地埋滴灌管：埋深 15cm，滴头间距 30cm，流量 1.6L/h
    S.append(cyl(20, LX, "x", (0, -330, -150), 14, "内嵌式滴灌管"))
    for i in range(8):
        S.append(emitter((150 + i * 300, -330, -138), "内嵌滴头"))
    # 上层种植土
    S.append(cut_soil(LX, 900, 110, (0, -260, -130), "上层种植土"))
    # ④ 表面蒲席草：压籽保湿，遮住出土口
    S.append(cut_soil(LX, 760, 22, (0, -120, -20), "蒲席草覆盖"))
    for i in range(11):
        S.append(box((LX, 26, 12), (0, -110 + i * 66, 0), "草秆"))

    # ③ 混播：细叶芒 5 · 狼尾草 3 · 蓝羊茅 2
    for i in range(5):
        S.append(tuft((190 + i * 470, 90 + (i % 2) * 180, 2), 820, 210, 7, 17, "细叶芒"))
    for i in range(3):
        S.append(tuft((330 + i * 760, 380, 2), 560, 170, 6, 15, "狼尾草"))
    # ⑤ 蓝羊茅怕涝，垫高 5cm 种（小土丘）
    for i in range(2):
        mx = 700 + i * 900
        S.append(cone(230, 170, 50, (mx, 60, 0), 16, "蓝羊茅垫高土丘"))
        S.append(tuft((mx, 60, 46), 330, 130, 7, 12, "蓝羊茅"))

    items = [("①", "排水层：原土掺三成粗砂，翻深 30cm", (600, -560, -450)),
             ("②", "滴灌管埋深 15cm，滴头间距 30cm", (750, -350, -132)),
             ("③", "混播 细叶芒 5 · 狼尾草 3 · 蓝羊茅 2", (1090, 380, 70)),
             ("④", "表面盖蒲席草，压籽保湿遮出土口", (1800, -120, -10)),
             ("⑤", "蓝羊茅怕涝，垫高 5cm 种", (700, 60, 120))]
    audit(items, S, -62, 20)
    print("saved", draw("0601-1", "地埋滴灌草原植床", items, S,
                        note="中段草原带按层做的植床，沿 5.3×18.9m 长条铺开；整床没有一条直线，但每株的位置都在图纸上",
                        sig="设想 · 0601", az=-62, el=20, fov=27))


