def fig2():
    """北段疏林带一棵朴树的树穴：切掉近侧一角的土，露出碎石排水、根球和环根球滴灌。"""
    S = []
    # 切开的地面：只留后方与左侧两块土，近右一角整块切掉
    S.append(cut_soil(2600, 900, 620, (-1300, 400, -620), "原土"))
    S.append(cut_soil(900, 800, 620, (-1300, -400, -620), "原土"))

    # ① 树穴 80cm 见方，底垫 10cm 碎石排水
    S.append(box((800, 800, 100), (-400, -400, -620), "碎石排水层"))
    S.append(gravel((-380, -380, -520), 760, 760, 20, 44, 28, "碎石"))

    # ② 根球（三角木桩撑住，歪着长也不倒）
    S.append(merge([cone(300, 250, 300, (0, 0, -520), 18, "根球"),
                    cone(250, 70, 160, (0, 0, -220), 18, "根球")], "根球"))

    # 朴树：歪脖子苗，树冠做成扁球
    trunk = []
    pts = [(0, 0, -260), (50, -30, 300), (-60, 20, 820), (90, -30, 1300), (50, 20, 1700)]
    for k in range(len(pts) - 1):
        trunk.append(seg_tube(pts[k], pts[k + 1], 90 - k * 13, 10, "朴树"))
    crowns = []
    for k in range(4):
        a = k * 1.7 + 0.4
        cx, cy = 50 + math.cos(a) * 520, 20 + math.sin(a) * 520
        cz = 1620 + (k % 2) * 180
        trunk.append(seg_tube((50, 20, 1560 - k * 90), (cx, cy, cz), 34, 8, "枝"))
        for m, (rr, hh) in enumerate(((260.0, 110.0), (360.0, 120.0), (300.0, 110.0), (170.0, 90.0))):
            crowns.append(cyl(rr, hh, "z", (cx, cy, cz + m * 100), 16, "树冠"))
    S.append(merge([t for t in trunk if t is not None], "朴树"))
    S.append(merge(crowns, "树冠"))

    # ③ 三角木桩 + 麻绳绑扎
    for k in range(3):
        a = k * 2 * math.pi / 3 + 0.9
        bx, by = math.cos(a) * 880, math.sin(a) * 880
        S.append(seg_tube((bx, by, -240), (math.cos(a) * 220, math.sin(a) * 220, 760), 45, 8, "三角木桩"))
        S.append(seg_tube((math.cos(a) * 220, math.sin(a) * 220, 720),
                          (math.cos(a) * 70, math.sin(a) * 70, 700), 13, 6, "麻绳"))
    S.append(path_tube([(math.cos(t) * 140, math.sin(t) * 140, 700) for t in np.linspace(0, 2 * math.pi, 15)],
                       13, 5, "麻绳"))

    # ④ 滴灌管环根球绕一圈，只露 3cm 出土口
    ring = [(math.cos(t) * 430, math.sin(t) * 430, -240) for t in np.linspace(0, 2 * math.pi, 19)]
    S.append(path_tube(ring, 18, 6, "环根球滴灌管"))
    S.append(path_tube([(430, 300, -240), (1250, 300, -240)], 18, 6, "滴灌干管"))
    S.append(merge([cyl(26, 200, "z", (700, -180, -240), 12, "出土口"),
                    cyl(36, 30, "z", (700, -180, -40), 12, "出土口帽")], "滴灌出土口"))
    S.append(path_tube([(330, -280, -240), (700, -180, -240)], 18, 6, "环根球滴灌管"))

    # ⑤ 碎树皮护根圈 φ1m、厚 8cm（整圈向上爆炸）
    MZ = 980.0
    S.append(merge([cyl(500, 80, "z", (0, 0, MZ), 24, "碎树皮护根圈"),
                    cyl(150, 84, "z", (0, 0, MZ - 2), 16, "树干孔")], "碎树皮护根圈"))
    S.append(gravel((-450, -450, MZ + 80), 900, 900, 22, 40, 20, "碎树皮"))

    items = [("①", "树穴 80cm 见方，底垫 10cm 碎石", (400, -400, -560)),
             ("②", "根球三角木桩撑住，歪着长也不倒", (250, -160, -380)),
             ("③", "三角木桩 + 麻绳绑扎，两年后拆", (math.cos(0.9) * 600, math.sin(0.9) * 600, 180)),
             ("④", "滴灌出土口只露 3cm，环管绕一圈", (718, -194, -85)),
             ("⑤", "碎树皮护根圈 φ1m、厚 8cm", (-480, -120, MZ + 40))]
    audit(items, S, -56, 22)
    print("saved", draw("0601-2", "疏林带朴树护根圈", items, S,
                        note="北段疏林带只种 3 棵朴树，沿东侧长边错开、间距 4m 以上；树皮慢慢腐烂就是肥",
                        sig="设想 · 0601", az=-56, el=22, fov=27))


