"""0105 PSK 工作台 — 两张硬件爆炸图（hand3d 管线）
0105-1 27 格零件柜 / 0105-2 头顶灯光机位总成
"""
import sys, os, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hand3d import box, cyl, extrusion
from partdraw import draw
from p01util import merge, audit

CE, DV, CA = 80, 8, 14          # 格 8×8cm / 格板 8 / 柜板 14
IW = 9 * CE + 8 * DV            # 内宽 784
IH = 3 * CE + 2 * DV            # 内高 256
DP = 80                         # 格深 ≤8cm
ZD = 740                        # 写字台面高


# ---------------------------------------------------------------- 0105-1
def fig1():
    X0, Z0 = CA, ZD + CA
    S = [box((1400, 700, 34), (-300, -520, ZD - 34), "写字台面")]

    # ① 白蜡木拼板柜体
    S += [box((CA, DP + 12, IH + 2 * CA), (0, -DP - 12, ZD), "白蜡木柜体"),
          box((CA, DP + 12, IH + 2 * CA), (IW + CA, -DP - 12, ZD), "白蜡木柜体"),
          box((IW + 2 * CA, DP + 12, CA), (0, -DP - 12, ZD), "白蜡木柜体"),
          box((IW + 2 * CA, DP + 12, CA), (0, -DP - 12, ZD + IH + CA), "白蜡木柜体"),
          box((IW + 2 * CA, 12, IH + 2 * CA), (0, -12, ZD), "柜背板")]
    # 柜里放几样小件
    S += [cyl(7, 62, "y", (120, -70, Z0 + 14), 10, "火石棒"),
          cyl(7, 62, "y", (146, -70, Z0 + 14), 10, "火石棒"),
          cyl(22, 18, "z", (276, -46, Z0 + 2), 14, "鱼线卷"),
          box((40, 30, 12), (370, -60, Z0 + 2), "别针盒")]

    # ② 纵向格板 ×8（抬出来）
    ZV = ZD + 470
    for i in range(1, 9):
        S.append(box((DV, DP, IH), (X0 + i * (CE + DV) - DV, -DP - 6, ZV), "纵向格板"))
        S.append(box((DV, 16, 10), (X0 + i * (CE + DV) - DV, -DP - 6, ZV - 10), "榫头"))
    # ③ 横向格板 ×2（再抬高一层）
    ZH = ZD + 820
    for j in (0, 1):
        S.append(box((IW, DP, DV), (X0, -DP - 6, ZH + j * 120), "横向格板"))
        for k in (1, 4, 7):
            S.append(box((14, 16, 8), (X0 + k * (CE + DV) + 32, -DP - 24, ZH + j * 120), "榫槽"))
    # ④ 27 格格底 3mm 毛毡
    ZF = ZD + 1085
    pads = []
    for r in range(3):
        for c in range(9):
            pads.append(box((CE - 4, DP - 8, 4), (X0 + c * (CE + DV) + 2, -DP - 2, ZF + r * 26), "毛毡衬垫"))
    S.append(merge(pads, "3mm 毛毡衬垫"))
    # ⑤ 格口激光刻标签条（往外拉出来）
    YL = -440
    lab = []
    for r in range(3):
        for c in range(9):
            lab.append(box((CE - 6, 3, 16), (X0 + c * (CE + DV) + 3, YL, Z0 + r * (CE + DV) + 4), "标签条"))
    S.append(merge(lab, "激光刻标签条"))

    items = [("①", "白蜡木拼板柜体，高 ≤25cm 不挡南窗", (4, -60, ZD + 150)),
             ("②", "纵向格板 ×8，榫槽插进柜体", (X0 + 4 * (CE + DV) - DV + 4, -DP - 6, ZV + 150)),
             ("③", "横向格板 ×2，分出上中下三排", (300, -DP - 6, ZH + 124)),
             ("④", "27 格各 8×8cm、深 ≤8cm，格底 3mm 毛毡", (X0 + 4 * (CE + DV) + 40, -DP - 2, ZF + 56)),
             ("⑤", "格口激光刻标签：物件名 + 标准数量", (X0 + 2 * (CE + DV) + 40, YL, Z0 + CE + DV + 12))]
    audit(items, S, -62, 22)
    p = draw("0105-1", "27 格零件柜", items, S,
             note="写字台靠里那一排：一格一物、从左到右，装配时手沿一条线走，不用找也不用想",
             sig="设想 · 0105", az=-62, el=22, fov=27)
    print("saved", p)


# ---------------------------------------------------------------- 0105-2
def fig2():
    ZC = 2400                       # 天花
    S = [box((1900, 900, 60), (-150, -700, ZC), "天花")]
    S[0].shade = False

    # ① 两根天花吊杆 + 30×30 铝型材横梁
    for x in (180, 1420):
        S += [cyl(16, 380, "z", (x, -180, 2010), 12, "天花吊杆"),
              box((90, 90, 16), (x - 45, -225, ZC - 16), "吊杆法兰"),
              box((70, 70, 20), (x - 35, -215, 1990), "梁夹")]
    S.append(extrusion(1600, "x", (100, -195, 1960), 30, "30×30 铝型材横梁"))
    # ② 线槽（走电与网线）
    S += [box((1480, 52, 46), (160, -198, 1990), "线槽"),
          box((1440, 10, 10), (180, -202, 2032), "线槽盖")]

    # ③ 1.2m 长条灯（装在靠前 200 处，爆炸下移）
    ZL = 1700
    S += [box((1200, 92, 66), (300, -400, ZL), "1.2m 长条灯"),
          box((1160, 70, 10), (320, -389, ZL - 10), "灯面"),
          box((60, 40, 120), (500, -375, ZL + 66), "灯吊码"),
          box((60, 40, 120), (1000, -375, ZL + 66), "灯吊码")]
    # ④ 防眩格栅
    ZG = 1545
    gr = [box((1160, 70, 26), (320, -389, ZG), "防眩格栅")]
    for i in range(11):
        gr.append(box((8, 70, 34), (330 + i * 105, -389, ZG), "格栅片"))
    S.append(merge(gr, "防眩格栅"))

    # ⑤ 俯拍摄像头 + 球头座
    S += [cyl(22, 150, "z", (1700, -300, 1790), 14, "球头座杆"),
          cyl(36, 44, "z", (1700, -300, 1746), 16, "球头"),
          box((124, 98, 78), (1638, -349, 1664), "俯拍摄像头"),
          cyl(27, 36, "z", (1700, -300, 1628), 16, "镜头")]

    # 台面与 A3 装配区
    S += [box((1800, 700, 34), (-50, -760, ZD - 34), "写字台面"),
          box((420, 300, 6), (620, -520, ZD), "A3 皮垫")]

    items = [("①", "30×30 铝型材横梁，两根天花吊杆", (760, -195, 1990)),
             ("②", "线槽走电与网线", (1150, -198, 2014)),
             ("③", "1.2m 长条灯 4000K Ra≥95，靠前 20cm", (760, -400, ZL + 34)),
             ("④", "防眩格栅，坐着抬头不刺眼", (700, -389, ZG + 14)),
             ("⑤", "俯拍摄像头球头座，正对 A3 装配区", (1680, -349, 1702))]
    audit(items, S, -58, 14)
    p = draw("0105-2", "头顶灯光机位总成", items, S,
             note="写字台伸进床板下的那 90cm 不在它下面，另补一条小灯带；光从手前方来，手不会挡住自己",
             sig="设想 · 0105", az=-58, el=14, fov=27)
    print("saved", p)


fig1()
fig2()
