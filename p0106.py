SW, SD, SH = 400, 400, 520      # 铸铁壳体 40×40，炉膛段高 520（连脚连顶板约 65cm）
ZL = 150                        # 炉脚高


# ---------------------------------------------------------------- 0106-1
def fig1():
    S = []
    # 炉台（防火石板）
    hp = box((760, 720, 44), (-180, -560, -44), "防火炉台"); hp.shade = False
    S.append(hp)
    # 炉脚 ×4 + ⑤ 抽拉灰盒
    for (dx, dy) in ((46, -46), (SW - 46, -46), (46, -SD + 46), (SW - 46, -SD + 46)):
        S.append(cyl(26, ZL, "z", (dx, dy, 0), 12, "炉脚"))
    S += [box((330, 350, 96), (35, -710, ZL + 6), "抽拉灰盒"),
          box((350, 22, 116), (25, -732, ZL - 4), "灰盒面板"),
          cyl(9, 110, "x", (145, -746, ZL + 54), 10, "灰盒拉手")]

    # 铸铁壳体：底 + 三面墙 + 前脸（留门洞）
    ZB = ZL + 110
    sh = [box((SW, SD, 22), (0, -SD, ZB), "铸铁壳体"),
          box((22, SD, SH), (0, -SD, ZB), "铸铁壳体"), box((22, SD, SH), (SW - 22, -SD, ZB), "铸铁壳体"),
          box((SW, 22, SH), (0, -SD, ZB), "铸铁壳体"),
          box((SW, 22, 56), (0, -SD + SD - 22 - 0, ZB), "铸铁壳体")]
    sh = sh[:4]
    sh += [box((SW, 24, 60), (0, -SD, ZB), "前脸"),           # 门下沿
           box((SW, 24, 74), (0, -SD, ZB + SH - 74), "前脸"),  # 门上沿
           box((36, 24, SH), (0, -SD, ZB), "前脸"), box((36, 24, SH), (SW - 36, -SD, ZB), "前脸")]
    S.append(merge(sh, "5kW 铸铁壳体"))

    # ④ 耐火砖内衬：左右后三片，往外拉开
    S += [box((32, SD - 60, SH - 120), (-700, -SD + 30, ZB + 30), "耐火砖内衬"),
          box((32, SD - 60, SH - 120), (SW + 660, -SD + 30, ZB + 30), "耐火砖内衬"),
          box((SW - 80, 32, SH - 120), (40, 470, ZB + 30), "耐火砖内衬")]
    for i in range(3):
        S.append(box((SW - 80, 6, 4), (40, 469, ZB + 30 + (i + 1) * 100), "砖缝"))

    # ③ 挡火板
    Z3 = ZB + SH + 260
    S += [box((SW - 70, SD - 130, 24), (35, -SD + 60, Z3), "挡火板"),
          box((SW - 70, 26, 56), (35, -SD + 60, Z3 + 24), "挡火板立边")]
    # ② 二次燃烧管
    Z2 = Z3 + 210
    S.append(cyl(26, SW - 110, "x", (55, -SD / 2 - 30, Z2), 14, "二次燃烧管"))
    for i in range(7):
        S.append(cyl(5, 26, "y", (86 + i * 42, -SD / 2 - 56, Z2), 8, "补风孔"))
    S.append(cyl(20, 120, "y", (SW - 70, -SD / 2 - 30, Z2), 12, "预热进风"))
    # ① 炉顶平板 + 水壶
    Z1 = Z2 + 220
    S += [box((SW + 60, SD + 60, 30), (-30, -SD - 30, Z1), "炉顶平板"),
          cyl(96, 130, "z", (200, -200, Z1 + 30), 18, "水壶"),
          cyl(40, 34, "z", (200, -200, Z1 + 160), 14, "壶盖"),
          cyl(11, 120, "x", (150, -320, Z1 + 120), 10, "壶嘴")]

    # ⑤ 微晶玻璃门（往前掀开）
    YD = -SD - 620
    dr = [box((330, 26, 340), (35, YD, ZB + 90), "微晶玻璃门"),
          box((286, 8, 296), (57, YD - 8, ZB + 112), "微晶玻璃")]
    S.append(merge(dr, "微晶玻璃门"))
    S.append(cyl(13, 90, "y", (355, YD - 90, ZB + 250), 12, "门把手"))

    items = [("①", "炉顶平板可烧水烤薯，5kW 约 40×40×65cm", (200, -SD - 30, Z1 + 30)),
             ("②", "二次燃烧管，给火焰顶部补预热空气", (240, -SD / 2 - 56, Z2)),
             ("③", "挡火板，逼烟气在炉膛里多绕一圈", (200, -SD + 60, Z3 + 24)),
             ("④", "耐火砖内衬，护铸铁不烧裂、先把热存住", (-668, -SD + 120, ZB + 260)),
             ("⑤", "微晶玻璃门耐 700℃，脚下抽拉灰盒", (200, YD - 8, ZB + 260))]
    audit(items, S, -56, 18)
    p = draw("0106-1", "铸铁柴火炉本体", items, S,
             note="西南角炉区 40×40：铸铁蓄热慢放，火熄了还能温两小时；明火和床同室，一氧化碳报警器必装",
             sig="设想 · 0106", az=-56, el=18, fov=27)
    print("saved", p)


