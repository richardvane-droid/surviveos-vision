TOTAL_MID, TOTAL_LOW, TOTAL_HIGH, TOTAL_OPEX = 255075, 173050, 337100, 10480


def build():
    mods, bom_count = {}, 0
    for code, (low, high, mid, opex, phase, note, bom) in C.items():
        assert low <= mid <= high, f"{code} 区间不合法：{low}/{mid}/{high}"
        assert 3 <= len(bom) <= 6, f"{code} BOM 条数 {len(bom)} 不在 3~6"
        s = sum(a for _, a in bom)
        assert s == mid, f"{code} BOM 合计 {s} ≠ 中位 {mid}"
        bom_count += len(bom)
        mods[code] = {
            "low": low, "high": high, "mid": mid, "opex": opex,
            "phase": phase, "phase_name": PHASES[phase], "note": note,
            "bom": [{"item": n, "amount": a, "pct": round(a / mid * 100, 1)} for n, a in bom],
        }

    order = sorted(mods, key=lambda c: -mods[c]["mid"])
    for i, c in enumerate(order, 1):
        mods[c]["rank"] = i
        mods[c]["share"] = round(mods[c]["mid"] / TOTAL_MID * 100, 2)

    def agg(codes):
        return {"n": len(codes),
                "low": sum(mods[c]["low"] for c in codes), "high": sum(mods[c]["high"] for c in codes),
                "mid": sum(mods[c]["mid"] for c in codes), "opex": sum(mods[c]["opex"] for c in codes)}

    areas = {}
    for c in mods:
        areas.setdefault(c[:2], []).append(c)
    area_agg = {a: {**agg(cs), "share": round(sum(mods[c]["mid"] for c in cs) / TOTAL_MID * 100, 1)}
                for a, cs in sorted(areas.items())}
    phase_agg = {str(p): {**agg([c for c in mods if mods[c]["phase"] == p]),
                          "name": PHASES[p],
                          "share": round(sum(mods[c]["mid"] for c in mods if mods[c]["phase"] == p) / TOTAL_MID * 100, 1)}
                 for p in (1, 2, 3)}

    total = agg(list(mods))
    assert (total["mid"], total["low"], total["high"], total["opex"]) == (TOTAL_MID, TOTAL_LOW, TOTAL_HIGH, TOTAL_OPEX), \
        f"合计对不上：{total}"
    assert bom_count == 224, f"BOM 条目数 {bom_count} ≠ 224"

    data = {"meta": {"updated": "2026-09-16", "currency": "CNY", "modules": len(mods),
                     "bom_items": bom_count, "avg_mid": round(TOTAL_MID / len(mods)),
                     "total": total, "areas": area_agg, "phases": phase_agg,
                     "top": order[:5], "cheap": order[-5:][::-1]},
            "modules": mods}
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"cost.json: {len(mods)} 模块 / {bom_count} 条支出 / 中位 ¥{TOTAL_MID:,} / 年度 ¥{TOTAL_OPEX:,}")


if __name__ == "__main__":
    build()
