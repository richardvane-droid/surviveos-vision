import sys, os, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
from hand3d import box, cyl, extrusion, Solid
from props import motor
from partdraw import draw
from p01util import merge, rot, prism, audit, screw

RAIL = 3000          # 滑轨 3m
Y = 320              # 滑轨中心线离梁内侧的距离


# ---------------------------------------------------------------- 0201-1
def fig1():
    S = []
    ZH, ZR, ZC, ZG, ZL = 2120, 1720, 1340, 900, 360     # 爆炸各层的高度

    # 楼板 + 南侧梁（只给够用的一块，纯背景）
    for b in (box((2700, 540, 70), (150, -230, 2660), "楼板"),
              box((2700, 220, 220), (150, -230, 2440), "南侧梁")):
        b.shade = False; S.append(b)

    # ④ 吊架 ×2：贴梁顶板 + 两片侧板 + 膨胀螺栓咬楼板
    for hx in (240, 2500):
        h = [box((264, 230, 18), (hx, Y - 115, ZH + 190), "吊架顶板"),
             box((16, 230, 190), (hx + 18, Y - 115, ZH), "吊架侧板"),
             box((16, 230, 190), (hx + 230, Y - 115, ZH), "吊架侧板"),
             box((264, 16, 104), (hx, Y - 115, ZH + 86), "贴梁立板")]
        S.append(merge(h, "吊架"))
        for dx, dy in ((46, -74), (218, -74), (46, 74), (218, 74)):
            S += screw((hx + dx, Y + dy, ZH + 208), 9, 150, "z", "膨胀螺栓")

    # ① 3m V 型滑轨（铝型材）+ 同步带 + 两端带轮
    S.append(extrusion(RAIL, "x", (0, Y - 32, ZR), 64, "V 型滑轨"))
    S.append(box((RAIL, 18, 20), (0, Y - 44, ZR + 22), "V 槽条"))
    S.append(box((RAIL, 18, 20), (0, Y + 26, ZR + 22), "V 槽条"))
    ZB = ZR - 92                                   # 同步带贴在滑轨底面
    belt = [cyl(34, 26, "x", (-40, Y, ZB), 16, "带轮"),
            cyl(34, 26, "x", (RAIL + 14, Y, ZB), 16, "带轮"),
            box((RAIL + 54, 12, 9), (-40, Y - 6, ZB + 25), "同步带"),
            box((RAIL + 54, 12, 9), (-40, Y - 6, ZB - 34), "同步带")]
    S.append(merge(belt, "同步带"))

    # ② NEMA17 步进电机 + 行星减速箱（东端）
    S.append(box((92, 76, 76), (-138, Y - 38, ZB - 38), "行星减速"))
    S += motor((-300, Y - 30, ZB - 30), 60, 162, "x", "NEMA17")

    # 滑车：车身 + 四只 V 轮 + 皮带夹
    car = [box((260, 170, 64), (1330, Y - 85, ZC - 32), "滑车")]
    for dx in (1352, 1556):
        for dy in (-74, 62):
            car.append(cyl(24, 14, "y", (dx + 18, Y + dy, ZC + 46), 12, "V 轮"))
    car.append(box((56, 32, 44), (1432, Y - 16, ZC + 32), "皮带夹"))
    S.append(merge(car, "滑车"))

    # ⑤ 拖链：一串链节沿滑轨方向，末端拐下去接滑车
    ch = []
    for i in range(10):
        ch.append(box((116, 76, 64), (170 + i * 130, Y + 90, ZR + 250), "拖链"))
    for i in range(3):
        ch.append(box((104, 76, 62), (1470 + i * 28, Y + 90, ZR + 228 - i * 62), "拖链"))
    S.append(merge(ch, "拖链"))

    # ③ 双轴云台：水平转盘 + U 形叉臂 + 俯仰轴
    g = [cyl(74, 62, "z", (1465, Y, ZG + 200), 18, "水平转盘"),
         cyl(52, 58, "z", (1465, Y, ZG + 142), 16, "水平轴"),
         box((300, 34, 190), (1315, Y - 128, ZG - 46), "叉臂"),
         box((300, 34, 190), (1315, Y + 94, ZG - 46), "叉臂"),
         box((300, 256, 34), (1315, Y - 128, ZG + 144), "叉臂横梁"),
         cyl(26, 254, "y", (1465, Y - 127, ZG + 34), 14, "俯仰轴")]
    S.append(merge(g, "双轴云台"))
    S.append(box((70, 62, 62), (1600, Y - 31, ZG + 4), "俯仰电机"))

    # 灯体（0201-2 细画）
    S.append(box((250, 300, 260), (1340, Y - 150, ZL), "FS-300B 灯体"))
    S.append(cyl(96, 110, "y", (1465, Y + 150, ZL + 130), 20, "保荣卡口"))
    S.append(box((190, 26, 190), (1370, Y - 178, ZL + 36), "散热网"))

    items = [("①", "3m 铝 V 型滑轨，同步带传动", (620, Y - 32, ZR + 64)),
             ("②", "NEMA17 + 减速，步数即位置", (-210, Y, ZR - 92)),
             ("③", "双轴云台：俯仰 ±45°、水平 180°", (1465, Y + 128, ZG + 60)),
             ("④", "吊架膨胀螺栓咬楼板与梁侧", (2630, Y, ZH + 208)),
             ("⑤", "拖链走线，随滑车伸缩不外露", (560, Y + 166, ZR + 282))]
    audit(items, S, 72, 16)
    p = draw("0201-1", "电动滑轨云台", items, S,
             note="南侧梁内侧天花板贴梁东西向固定；梁底 2400 就是灯的高度上限，灯 + 云台 + 线缆约 6kg，按 3 倍冗余",
             sig="设想 · 0201", az=72, el=16, fov=27)
    print("saved", p)


# ---------------------------------------------------------------- 0201-2
def fig2():
    S = []
    CX, CZ = 0, 0
    Y0, Y1, Y2, Y3 = 0, 620, 1060, 1440

    # ① FS-300B 灯体：机身 + 散热风扇 + COB 灯头
    b = [box((250, 300, 260), (CX - 125, Y0, CZ - 130), "FS-300B 机身"),
         box((196, 22, 196), (CX - 98, Y0 - 22, CZ - 98), "散热格栅"),
         box((150, 40, 46), (CX - 75, Y0 + 60, CZ - 176), "双色温旋钮区")]
    S.append(merge(b, "FS-300B 机身"))
    S.append(cyl(64, 120, "y", (CX, Y0 + 300, CZ), 20, "COB 灯头"))
    S.append(cyl(46, 16, "y", (CX, Y0 + 418, CZ), 18, "COB 发光面"))

    # ② 保荣卡口 + 菲涅尔透镜筒 Φ200
    S.append(cyl(84, 56, "y", (CX, Y1, CZ), 22, "保荣卡口"))
    for i in range(6):
        a = i * math.pi / 3
        S.append(box((30, 56, 22), (CX + math.cos(a) * 84 - 15, Y1, CZ + math.sin(a) * 84 - 11), "卡爪"))
    S.append(cyl(104, 210, "y", (CX, Y1 + 62, CZ), 24, "透镜筒"))
    # 透镜：同心环截面（用 5 个薄环表示菲涅尔的一圈圈）
    for k, rr in enumerate((100, 80, 60, 40, 20)):
        S.append(cyl(rr, 9, "y", (CX, Y1 + 272 + k * 5, CZ), 24, "菲涅尔环"))
    # ③ 调焦：筒侧滑槽 + 旋钮
    S.append(box((22, 168, 26), (CX + 104, Y1 + 82, CZ - 13), "调焦滑槽"))
    S.append(cyl(30, 46, "x", (CX + 116, Y1 + 150, CZ), 14, "调焦旋钮"))

    # ④ 椴木窗棂遮片（双格）
    fr = [box((300, 20, 20), (CX - 150, Y2, CZ - 150), "遮片框"),
          box((300, 20, 20), (CX - 150, Y2, CZ + 130), "遮片框"),
          box((20, 20, 300), (CX - 150, Y2, CZ - 150), "遮片框"),
          box((20, 20, 300), (CX + 130, Y2, CZ - 150), "遮片框"),
          box((14, 18, 260), (CX - 7, Y2 + 1, CZ - 130), "窗棂"),
          box((260, 18, 14), (CX - 130, Y2 + 1, CZ - 7), "窗棂")]
    S.append(merge(fr, "椴木窗棂遮片"))
    S.append(box((70, 14, 56), (CX + 156, Y2 + 3, CZ - 28), "插片手柄"))

    # ⑤ 铝制四叶挡光板：方框座 + 四片各自绕铰链外翻 30°
    rim = [box((340, 30, 26), (CX - 170, Y3, CZ - 170), "挡光板座"),
           box((340, 30, 26), (CX - 170, Y3, CZ + 144), "挡光板座"),
           box((26, 30, 314), (CX - 170, Y3, CZ - 144), "挡光板座"),
           box((26, 30, 314), (CX + 144, Y3, CZ - 144), "挡光板座")]
    S.append(merge(rim, "挡光板座"))
    YH, LF = Y3 + 30, 230
    # 上片（铰链 z=+157，往 +Y 外翻）
    S.append(rot(box((320, 9, LF), (CX - 160, YH, CZ + 157), "四叶挡光板"),
                 -30, "x", (CX, YH, CZ + 157)))
    # 下片（铰链 z=-157）
    S.append(rot(box((320, 9, LF), (CX - 160, YH, CZ - 157 - LF), "四叶挡光板"),
                 30, "x", (CX, YH, CZ - 157)))
    # 右片（铰链 x=+157）
    S.append(rot(box((LF, 9, 320), (CX + 157, YH, CZ - 160), "四叶挡光板"),
                 30, "z", (CX + 157, YH, CZ)))
    # 左片（铰链 x=-157）
    S.append(rot(box((LF, 9, 320), (CX - 157 - LF, YH, CZ - 160), "四叶挡光板"),
                 -30, "z", (CX - 157, YH, CZ)))

    items = [("①", "南光 FS-300B：300W COB 双色温", (CX, Y0 + 150, CZ + 130)),
             ("②", "保荣卡口 + 菲涅尔透镜 Φ200", (CX, Y1 + 290, CZ + 96)),
             ("③", "前后调焦，光斑 15°~55° 可变", (CX + 130, Y1 + 150, CZ)),
             ("④", "椴木激光切窗棂遮片，双 / 三格", (CX - 7, Y2 + 10, CZ + 90)),
             ("⑤", "铝制四叶挡光板，硬光下不变形", (CX, Y3 + 150, CZ + 300))]
    audit(items, S, 64, 20)
    p = draw("0201-2", "菲涅尔假窗光学组", items, S,
             note="灯挂在滑车云台下，光轴朝北打向西北角的床；透镜把散光压成硬光，墙上才会有真实日光的窗格影子",
             sig="设想 · 0201", az=64, el=20, fov=27)
    print("saved", p)


fig1()
fig2()
