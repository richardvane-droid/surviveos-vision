def chain(top, n=6, rad=30, wire=6, pitch=64, name="链条"):
    o = []
    for k in range(n):
        z = top[2] - pitch * k
        pl = "xz" if k % 2 == 0 else "yz"
        o.append(path_tube(arc_pts((top[0], top[1], z), rad, 0, 360, 10, pl), wire, 6, name))
    return merge(o, name)


