    S.append(box((44, 30, 44), (20, Y(0) + 6, 16), "接线端子"))
    # ④ 继电器 + 12V 小电源
    S.append(box((70, 22, 54), (-64, Y(1), 22), "16A 继电器"))
    S.append(box((56, 18, 40), (14, Y(1) + 2, 28), "电源模块"))
    # ③ BL0937 计量芯片小板
    S.append(box((136, 6, 96), (-68, Y(2), 12), "计量主板"))
    S.append(box((26, 5, 26), (-44, Y(2) - 5, 50), "BL0937"))
    S.append(cyl(16, 22, "y", (26, Y(2) + 3, 40), 14, "取样电流互感器"))
