from p56util import (merge, rot, mv, prism, path_tube, seg_tube, arc_pts, cone,
                     audit, patch, gravel, post_base, corrugate)

PS = 150.0        # 15cm 方杉木柱
PH = 1600.0       # 柱高 1.6m


# ---------------------------------------------------------------- 0505-1
def fig1():
    S = []
    S.append(patch(2300, 1900, (-820, -1150, 0), 60))
    # 东南角 1×2m 青石板停车位
    S.append(box((760, 1700, 70), (-1000, -1100, -70), "青石板停车位"))

    # ① 15cm 方杉木柱（背面开走线凹槽）
    S.append(box((PS, PS, PH), (0, 0, 50), "15cm 方杉木柱"))
    S.append(box((60, 18, PH - 120), (45, PS - 18, 110), "背面走线凹槽"))
    # 盖槽木条（向 +Y 爆炸）
    S.append(box((70, 20, PH - 140), (40, PS + 460, 130), "盖槽木条"))

    # ② 镀锌柱脚：架空 5cm，不直接埋土（整组向下爆炸）
    BSY = -880.0
    S.append(box((PS + 90, PS + 90, 16), (-45, BSY - 45, 0), "镀锌柱脚底板"))
    for dx in (-8.0, PS - 4):
        S.append(box((12, PS, 130), (dx, BSY, 16), "镀锌柱脚夹板"))
    for (dx, dy) in ((-20.0, -20.0), (PS + 8, PS + 8)):
        S.append(cyl(11, 90, "z", (dx, BSY + dy, -90), 10, "膨胀螺栓"))
    # 地下 PVC 穿线管
    S.append(path_tube([(PS / 2, PS - 8, 60), (PS / 2, PS - 8, -520),
                        (PS / 2, -900, -520)], 26, 8, "地下 PVC 管"))

    # ③ 40cm 坡屋檐（整个向上爆炸）
    RZ = PH + 50 + 300
    roof = corrugate(560, 520, (-205, -185, RZ), 4, 46, "坡屋檐")
    S.append(rot(roof, 14, "x", (75, 75, RZ)))
    S.append(box((260, 260, 60), (-55, -55, RZ - 90), "檐下垫木"))
    # 屋檐正下方的人体感应暖光灯
    S.append(merge([cyl(70, 86, "z", (75, 20, RZ - 250), 16, "人体感应暖光灯"),
                    cyl(50, 20, "z", (75, 20, RZ - 270), 14, "灯罩"),
                    box((56, 34, 30), (47, -14, RZ - 216), "感应窗")], "人体感应暖光灯"))

    # ④ 防水插座 + 卷线盘（1.2m 高，向 -Y 爆炸）
    SKZ = 1250.0
    S.append(box((160, 26, 220), (-5, -540, SKZ), "防水插座"))
    S.append(box((130, 16, 150), (10, -556, SKZ + 30), "翻盖"))
    S.append(merge([cyl(130, 110, "y", (75, -900, SKZ - 120), 20, "卷线盘"),
                    cyl(150, 14, "y", (75, -900, SKZ - 120), 20, "盘侧板"),
                    cyl(150, 14, "y", (75, -790, SKZ - 120), 20, "盘侧板")], "卷线盘"))
    S.append(path_tube([(75, -845, SKZ - 250), (75, -700, SKZ - 420), (300, -520, SKZ - 560)], 13, 6, "充电线"))
    S.append(seg_tube((75, -520, SKZ + 110), (75, -14, SKZ + 110), 11, 6, "接线"))

    # ⑤ 背面三个铸铁挂钩：头盔 / 雨衣 / 充气泵（向 +Y 爆炸）
    for i, dz in enumerate((1380.0, 1080.0, 780.0)):
        hy = PS + 420
        S.append(merge([box((40, 130, 22), (55, hy, dz), "铸铁挂钩"),
                        box((40, 22, 70), (55, hy + 108, dz - 48), "铸铁挂钩")], "铸铁挂钩"))
    S.append(merge([cone(120, 150, 130, (75, PS + 780, 1300), 16, "头盔"),
                    cone(150, 60, 90, (75, PS + 780, 1430), 16, "头盔")], "头盔"))
    S.append(merge([box((220, 30, 380), (-35, PS + 700, 690), "雨衣"),
                    box((150, 26, 90), (0, PS + 704, 1070), "雨衣肩")], "雨衣"))
    S.append(merge([box((130, 110, 180), (10, PS + 720, 430), "充气泵"),
                    cyl(26, 90, "y", (75, PS + 700, 520), 12, "泵口")], "充气泵"))

    items = [("①", "15cm 方杉木柱 1.6m，背面走线槽", (PS, 40, 900)),
             ("②", "镀锌柱脚架空 5cm，不直接埋土", (PS - 4, BSY, 90)),
             ("③", "40cm 坡屋檐挡雨，檐下感应灯", (75, -50, RZ - 205)),
             ("④", "防水插座与卷线盘装在 1.2m 高", (-5, -540, SKZ + 160)),
             ("⑤", "背面三挂钩：头盔 / 雨衣 / 充气泵", (95, PS + 440, 1402))]
    audit(items, S, -50, 16)
    print("saved", draw("0505-1", "杉木充电桩柱", items, S,
                        note="立在庭院东南角的弧形雨棚下；电线走柱背凹槽 + 地下 PVC 管接到木屋配电箱，电摩从 2m 过道直接推进来",
                        sig="设想 · 0505", az=-50, el=16, fov=27))


