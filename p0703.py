# ---------------------------------------------------------------- 0703-1
def fig1():
    """在水平坐标里叠好各层，最后整组绕 X 转 15° 贴到顶棚向阳坡面上。"""
    G = []

    # 顶棚檩条（背景）+ 竹瓦屋面
    for y in (60.0, 620.0, 1180.0):
        p = box((1600, 90, 90), (-100, y, -90), "顶棚檩条")
        G.append(p)
    tiles = [cyl(80, 1400, "y", (60 + i * 170, 0, 0), 10, "竹瓦") for i in range(9)]
    G.append(merge(tiles, "竹瓦屋面"))

    # ② 铝支架：两根导轨 + 四个垫脚（沿法向拉起 340）
    ER = 330.0
    for x in (180.0, 1120.0):
        G.append(box((60, 900, 50), (x, 250, ER), "铝合金支架导轨"))
        for y in (300.0, 1060.0):
            G.append(box((80, 70, 120), (x - 10, y, ER - 120), "支架垫脚"))

    # ③ M8 不锈钢螺栓穿檩条固定（拉到导轨与屋面之间）
    for x in (210.0, 1150.0):
        for y in (335.0, 1095.0):
            G.append(cyl(8, 190, "z", (x, y, 200), 10, "M8 不锈钢螺栓"))
            G.append(cyl(16, 16, "z", (x, y, 390), 10, "螺栓头"))
            G.append(cyl(15, 10, "z", (x, y, 180), 10, "不锈钢垫片"))

    # ① 200W 单晶光伏板 1.1×0.7m（再往法向拉起）
    EP = ER + 360
    pan = [box((1100, 700, 35), (100, 320, EP), "200W 单晶光伏板"),
           box((1100, 34, 44), (100, 320, EP - 5), "铝边框"),
           box((1100, 34, 44), (100, 986, EP - 5), "铝边框"),
           box((34, 700, 44), (100, 320, EP - 5), "铝边框"),
           box((34, 700, 44), (1166, 320, EP - 5), "铝边框")]
    for i in range(1, 4):
        pan.append(box((8, 700, 38), (100 + i * 275, 320, EP + 34), "栅线"))
    G.append(merge(pan, "200W 单晶光伏板"))

    # ④ 四角 5cm 通风缝：在板背四角各画一个通风垫块
    for x in (150.0, 1150.0):
        for y in (370.0, 936.0):
            G.append(box((60, 60, 50), (x, y, EP - 50), "四角通风垫块 50mm"))

    # ⑤ MC4 防水插头 + 走檐下的线（低边在 -Y 一侧，也就是相机这侧的檐口）
    my = 320.0
    for x in (420.0, 560.0):
        G.append(capped_cyl(24, 130, "y", (x, my - 140, EP - 66), 12, "MC4 防水插头"))
        G.append(capped_cyl(15, 140, "y", (x, my - 280, EP - 66), 10, "光伏线"))
        G.append(path_tube([(x, my - 280, EP - 66), (x, my - 450, EP - 200),
                            (x + 60, my - 540, EP - 430)], 14, 8, "光伏线"))

    S = rot(G, PITCH, "x", (0, 0, 0))

    def R(p):
        a = math.radians(PITCH)
        return (p[0], p[1] * math.cos(a) - p[2] * math.sin(a), p[1] * math.sin(a) + p[2] * math.cos(a))

    items = [("①", "200W 单晶光伏板 1.1×0.7m", R((500, 600, EP + 35))),
             ("②", "铝支架垫出 15° 倾角，与棚坡一致", R((210, 300, ER + 50))),
             ("③", "M8 不锈钢螺栓穿檩条固定", R((1150, 1095, 390))),
             ("④", "四角留 5cm 通风缝，板背散热", R((104, 340, EP - 5))),
             ("⑤", "MC4 防水插头，线走檐下不淋雨", R((420, my - 200, EP - 66)))]
    audit(items, S, -58, 34)
    print("saved", draw("0703-1", "顶棚光伏板支架总成", items, S,
                        note="板贴在钓台顶棚 2.2×2m 的向阳坡面上，铝支架倾角与棚坡一致；接头都在檐下淋不到雨",
                        sig="设想 · 0703", az=-58, el=34, fov=27))


