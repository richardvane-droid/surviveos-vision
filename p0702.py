def hole_grid(x0, z0, nx, nz, pitch, y, r=9, name="孔距 25mm 通用孔"):
    """洞洞板孔位：只画一小片示意圆，作为特征线贴在板面上。"""
    E = []
    for i in range(nx):
        for j in range(nz):
            cx, cz = x0 + i * pitch, z0 + j * pitch
            th = np.linspace(0, 2 * math.pi, 9)
            pp = [np.array([cx + r * math.cos(t), y, cz + r * math.sin(t)]) for t in th]
            E += [(pp[k], pp[k + 1]) for k in range(8)]
    return Solid([], E, name)


def rod(pos, L, tilt, r0=16, r1=4, name="鱼竿"):
    """一根渐细的鱼竿：圆台绕 Y 转 tilt 度（0=竖直，90=水平指向 +X）。"""
    return rot(cone(r0, r1, L, pos, 10, name), tilt, "y", pos)


