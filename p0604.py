def fig2():
    """中段东缘乌桕树下：浅水盆 + 桧木喂鸟器，离东墙 4m 正对长焦。"""
    S = []
    S.append(patch(2700, 2000, (-1250, -950, 0), 60))

    # 乌桕树干（只给一小段，示意树下）
    S.append(seg_tube((-1080, 860, 0), (-1030, 900, 1560), 92, 12, "乌桕"))
    for k in range(3):
        a = k * 2.0 + 0.5
        S.append(seg_tube((-1035, 890, 1120 + k * 190),
                          (-1035 + math.cos(a) * 480, 890 + math.sin(a) * 480, 1560 + k * 130), 38, 8, "枝"))
    bush = []
    for k in range(5):
        a = k * 1.27
        bx2, by2 = 1160 + math.cos(a) * 190, 700 + math.sin(a) * 150
        h2 = 180 + (k % 3) * 90
        bush.append(cone(120, 210, h2 * 0.55, (bx2, by2, 0), 12, "灌木"))
        bush.append(cone(210, 60, h2 * 0.55, (bx2, by2, h2 * 0.55), 12, "灌木"))
    S.append(merge(bush, "灌木"))
    S.append(grass_row((-1000, -860, 0), (-260, -860, 0), 3, 400, 150, "细叶芒"))

    # ① 浅陶盆 Φ40cm，水深 3~5cm
    BX, BY = 0.0, 0.0
    S.append(merge([cone(170, 200, 90, (BX, BY, 120), 22, "浅陶盆"),
                    cyl(212, 26, "z", (BX, BY, 184), 22, "盆沿")], "浅陶盆"))
    S.append(disc(186, (BX, BY, 172), "z", 22, "水面"))
    # 斜石踏板
    S.append(rot(prism([(0, 0), (190, -20), (210, 150), (20, 170)], 130, "z", (BX + 40, BY - 100, 120), "斜石踏板"),
                 -22, "y", (BX + 140, BY - 20, 180)))

    # ② 12V 加热垫 10W（从盆底向下爆炸）
    S.append(merge([cyl(150, 16, "z", (BX - 620, BY - 400, 10), 20, "12V 加热垫"),
                    cyl(120, 8, "z", (BX - 620, BY - 400, 26), 18, "发热膜")], "12V 加热垫"))
    S.append(path_tube([(BX - 620, BY - 250, 18), (BX - 620, BY - 30, 18), (BX - 180, BY - 30, 18)], 11, 6, "加热垫线"))
    # 盆架：三块砖
    for k in range(3):
        a = k * 2 * math.pi / 3 + 0.4
        S.append(box((150, 90, 120), (BX + math.cos(a) * 130 - 75, BY + math.sin(a) * 130 - 45, 0), "垫砖"))

    # ③④ 桧木喂鸟器 20×20cm：立柱 + 托盘 + 四角柱 + 坡屋顶
    FX, FY = 900.0, -180.0
    S.append(box((110, 110, 1100), (FX - 55, FY - 55, 0), "喂鸟器立柱"))
    S.append(box((320, 320, 40), (FX - 160, FY - 160, 1100), "喂鸟器底板"))
    for (dx, dy) in ((-140.0, -140.0), (140.0, -140.0), (-140.0, 140.0), (140.0, 140.0)):
        S.append(box((36, 36, 240), (FX + dx - 18, FY + dy - 18, 1140), "角柱"))
    # 托盘（可抽出清洗，向 -Y 爆炸）
    TY = FY - 620
    tray = [box((260, 260, 18), (FX - 130, TY - 130, 1160), "可抽出托盘")]
    for (ox, oy, ow, od) in ((-130, -130, 260, 20), (-130, 110, 260, 20), (-130, -110, 20, 220), (110, -110, 20, 220)):
        tray.append(box((ow, od, 46), (FX + ox, TY + oy, 1178), "托盘沿"))
    S.append(merge(tray, "可抽出托盘"))
    # 葵花籽与苹果块
    for k in range(9):
        a = k * 1.4
        S.append(cyl(13, 9, "z", (FX + math.cos(a) * 70, TY + math.sin(a) * 70, 1196), 8, "葵花籽"))
    S.append(box((70, 70, 40), (FX + 20, TY - 30, 1196), "苹果块"))
    # 坡屋顶（向上爆炸）
    RZ = 1640.0
    S.append(rot(box((380, 380, 26), (FX - 190, FY - 190, RZ), "喂鸟器屋顶"), 18, "x", (FX, FY, RZ)))
    S.append(box((60, 60, 50), (FX - 30, FY - 30, RZ - 90), "屋脊垫木"))

    items = [("①", "浅陶盆 Φ40cm，水深 3~5cm 斜石踏板", (BX + 212, BY - 40, 190)),
             ("②", "12V 加热垫 10W，低于 2℃ 自动通电", (BX - 480, BY - 400, 16)),
             ("③", "桧木喂鸟器 20×20cm，屋顶挡雨四周敞开", (FX - 100, FY - 151, RZ - 22)),
             ("④", "托盘可抽出清洗，放葵花籽和苹果块", (FX - 130, TY - 130, 1200)),
             ("⑤", "离灌木 2m 以上，离东墙 4m 正对长焦", (1330, 395, 150))]
    audit(items, S, -58, 18)
    print("saved", draw("0604-2", "浅水盆与桧木喂鸟器", items, S,
                        note="都放在中段东缘的乌桕下，离灌木 2m 以上野猫没处埋伏；想让鸟来，先给水再给吃的",
                        sig="设想 · 0604", az=-58, el=18, fov=27))


