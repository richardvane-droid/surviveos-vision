def fig1():
    """建筑东墙 ≈4m 高处的一根横臂：两只眼睛一只耳朵。"""
    S = []
    # 只给够用的一块东墙（墙面朝 +X），墙上是阁楼檐口
    S.append(wall(1300, 1000, 180, (-180, -760, -560), "y", "建筑东墙"))
    S.append(box((460, 1300, 120), (-420, -760, 440), "阁楼檐口"))

    # ① 热镀锌横臂 Φ40×60cm + 墙板 + 膨胀螺栓
    S.append(capped_cyl(AR, AL, "x", (0, 0, 0), 20, "热镀锌横臂"))
    S.append(box((26, 190, 190), (-26, -95, -95), "臂根墙板"))
    for (dy, dz) in ((-62.0, -62.0), (62.0, -62.0), (-62.0, 62.0), (62.0, 62.0)):
        S += screw((-260, dy, dz), 9, 240, "x", "膨胀螺栓")

    # ② 广角机 2.8mm：臂端，朝北（-Y）俯拍整条 18.9m 草地
    WX = AL - 30
    S.append(rot(cam_body((WX, -400, -260), 46, 150, 2.8, "广角机 2.8mm"), -22, "x", (WX, -400, -260)))
    S.append(seg_tube((WX, -60, -70), (WX, -330, -210), 14, 8, "球头支臂"))
    S.append(cyl(30, 40, "z", (WX, -40, -AR - 40), 14, "臂端抱箍"))

    # ③ 长焦机 12mm：臂中，对准 4m 外乌桕下的水盆
    TXp = AL * 0.42
    S.append(rot(cam_body((TXp, -660, -470), 40, 130, 12, "长焦机 12mm"), -34, "x", (TXp, -660, -470)))
    S.append(seg_tube((TXp, -40, -60), (TXp, -600, -400), 13, 8, "球头支臂"))
    S.append(cyl(30, 40, "z", (TXp, -20, -AR - 40), 14, "臂中抱箍"))

    # ④ 防风毛套麦克风（绑在臂身上，向 +Y 爆炸）
    MX = AL * 0.72
    S.append(merge([cyl(26, 180, "y", (MX, 220, 30), 16, "麦克风"),
                    cyl(46, 140, "y", (MX, 246, 30), 16, "防风毛套"),
                    box((66, 26, 66), (MX - 33, 392, -2), "麦克风夹")], "防风毛套麦克风"))
    for k in range(9):
        S.append(cyl(50, 6, "y", (MX, 252 + k * 15, 30), 16, "毛套"))
    S.append(seg_tube((MX, 220, 30), (MX, 26, 2), 10, 6, "麦克风线"))

    # ⑤ 850nm 红外补光（挂在臂下，向下爆炸）+ PoE 网线穿墙
    IX = AL * 0.2
    S.append(merge([box((180, 130, 70), (IX - 90, -220, -420), "850nm 红外补光"),
                    box((150, 16, 46), (IX - 75, -236, -408), "红外灯板")] +
                   [cyl(15, 10, "y", (IX - 56 + k * 28, -238, -385), 10, "红外灯珠") for k in range(5)],
                   "850nm 红外补光"))
    S.append(seg_tube((IX, -AR, -30), (IX, -180, -350), 12, 6, "补光支臂"))
    S.append(path_tube([(WX, -34, -34), (140, -34, -34), (140, 0, -34), (-120, 0, -34)], 11, 6, "PoE 网线"))
    S.append(cyl(34, 200, "x", (-260, 0, -34), 12, "穿墙管"))

    items = [("①", "热镀锌横臂 Φ40mm×60cm，膨胀螺栓", (AL * 0.55, -13, 15)),
             ("②", "广角机 2.8mm 朝北拍 18.9m 全景", (WX + 46, -430, -232)),
             ("③", "长焦机 12mm 对准 4m 外的水盆", (TXp + 40, -690, -442)),
             ("④", "防风毛套麦克风，给 BirdNET 听叫声", (MX, 320, 76)),
             ("⑤", "850nm 红外补光 + 一根 PoE 网线穿墙", (IX - 90, -220, -380))]
    audit(items, S, -46, 14)
    print("saved", draw("0604-1", "东墙双机横臂", items, S,
                        note="装在木屋东墙上方、阁楼檐下 ≈4m 高处；太阳在东边侧照不逆光，夜里刺猬也能拍到",
                        sig="设想 · 0604", az=-46, el=14, fov=27))


