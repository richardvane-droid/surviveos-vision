AR = 20.0        # 横臂 Φ40mm
AL = 600.0       # 横臂 60cm


def cam_body(pos, r=46, L=150, lens=12, name="摄像头"):
    """筒机：机身 + 镜头 + 遮阳罩 + 支臂座。朝 -Y 看。"""
    x, y, z = pos
    o = [capped_cyl(r, L, "y", (x, y, z), 20, name),
         cyl(r * 0.62, 34, "y", (x, y - 34, z), 16, name + "镜筒"),
         disc(r * 0.62, (x, y - 34, z), "y", 16, name + "镜面"),
         box((r * 2.1, L * 0.8, 10), (x - r * 1.05, y + 10, z + r - 2), name + "遮阳罩"),
         box((30, 40, 54), (x - 15, y + L * 0.45, z - r - 54), name + "支臂座")]
    if lens >= 10:
        o.append(cyl(r * 0.5, 44, "y", (x, y - 78, z), 16, name + "长焦镜头"))
        o.append(disc(r * 0.5, (x, y - 78, z), "y", 16, name + "镜面"))
    return merge(o, name)


