# ---------------------------------------------------------------- 0306-1
def fig1():
    S = []
    # 45° 屋面一小块（南坡，外法线朝 -Y +Z）：杆从天窗边伸出屋面
    L = [box((1300, 1100, 70), (-560, -600, -70), "屋面")]
    for i in range(5):
        L.append(box((1300, 50, 22), (-560, -560 + i * 260, 0), "瓦垄"))
    L.append(box((420, 40, 90), (-500, 420, 0), "天窗上沿"))
    S += [ghost(x) for x in slope_frame([merge(L, "45° 屋面")], 45, (0, 0, 0))]

    # ③ 铰链底座 + 插销（台风天可放倒）
    BZ = 320.0
    S.append(box((300, 300, 40), (-150, -150, BZ - 40), "铰链底板"))
    for dx in (-90.0, 60.0):
        S.append(box((30, 150, 190), (dx, -75, BZ), "铰链耳板"))
    S.append(cyl(20, 260, "x", (-140, 0, BZ + 80), 14, "铰链轴"))
    S.append(cyl(13, 300, "x", (-160, 0, BZ + 160), 12, "插销"))
    S.append(path_tube(arc_pts((170, 0, BZ + 160), 34, -80, 240, 10, "yz"), 7, 6, "插销环"))

    # 铝合金杆 1.5m
    PZ0 = BZ + 60
    S.append(cyl(26, 1500, "z", (0, 0, PZ0), 16, "铝合金杆"))

    # ② 百叶盒（杆中段，沿 -Y 爆炸出来）+ BME280
    LY = -620.0
    for i in range(6):
        pl = box((250, 250, 16), (-125, LY - 125, PZ0 + 430 + i * 46), "百叶片")
        S.append(rot(pl, -18, "x", (0, LY, PZ0 + 438 + i * 46)))
    S.append(box((26, 26, 300), (-130, LY - 130, PZ0 + 420), "百叶立柱"))
    S.append(box((26, 26, 300), (105, LY - 130, PZ0 + 420), "百叶立柱"))
    S.append(box((90, 60, 16), (-45, LY - 30, PZ0 + 360), "BME280 小板"))
    S.append(box((22, 16, 10), (-15, LY - 24, PZ0 + 376), "BME280"))
    S.append(path_tube([(0, LY, PZ0 + 560), (0, -180, PZ0 + 640)], 8, 6, "传感线"))

    # 杆顶横臂（爆炸后三件各自抬起）
    TZ = PZ0 + 1500
    S.append(box((2700, 60, 60), (-1350, -30, TZ), "顶部横臂"))

    # ① 风杯（三只杯 + 竖轴），爆炸抬高
    CX, CZ = -1080.0, TZ + 260
    S.append(cyl(14, 260, "z", (CX, 0, CZ - 200), 12, "风杯轴"))
    S.append(cyl(46, 26, "z", (CX, 0, CZ + 60), 14, "风杯毂"))
    for i in range(3):
        a = i * 2 * math.pi / 3
        ex, ey = CX + 190 * math.cos(a), 190 * math.sin(a)
        S.append(path_tube([(CX, 0, CZ + 72), (ex, ey, CZ + 72)], 9, 6, "风杯臂"))
        S.append(cone(34, 62, 76, (ex, ey, CZ + 40), 16, "风杯"))
    # ① 风向标（箭头 + 尾翼），爆炸抬高
    VX, VZ = 40.0, TZ + 300
    S.append(cyl(14, 240, "z", (VX, 0, VZ - 200), 12, "风向标轴"))
    S.append(box((420, 16, 40), (VX - 210, -8, VZ + 40), "风向标杆"))
    S.append(cone(46, 8, 130, (VX + 210, 0, VZ + 60), 14, "标头"))
    S.append(rot(box((170, 14, 170), (VX - 240, -7, VZ - 20)), 0, "x", (0, 0, 0)))
    S.append(box((170, 14, 170), (VX - 250, -7, VZ - 24), "尾翼"))
    # ① 翻斗式雨量筒，爆炸抬高；翻斗从筒里再拆出来
    RX, RZ = 1120.0, TZ + 210
    S.append(cone(70, 170, 200, (RX, 0, RZ + 230), 20, "雨量筒集水漏斗"))
    S.append(cyl(160, 240, "z", (RX, 0, RZ - 10), 20, "雨量筒身"))
    S.append(box((320, 16, 240), (RX - 160, -8, RZ - 10), "筒身开窗"))
    S.append(box((230, 110, 14), (RX + 260, -55, RZ + 70), "翻斗底"))
    for dx in (0.0, 216.0):
        S.append(box((14, 110, 90), (RX + 260 + dx, -55, RZ + 84), "翻斗隔"))
    S.append(cyl(9, 150, "y", (RX + 375, -75, RZ + 60), 10, "翻斗轴"))

    items = [("①", "风杯 + 风向标 + 翻斗雨量筒", (CX, 0, CZ + 74)),
             ("②", "百叶盒内 BME280，测温湿压", (0, LY - 90, PZ0 + 520)),
             ("③", "铰链底座 + 插销，台风天可放倒", (-30, -75, BZ + 90)),
             ("④", "铝合金杆 1.5m，离屋脊 ≥1m", (0, -26, PZ0 + 1080)),
             ("⑤", "翻斗每翻一次约 0.28mm 雨", (RX + 375, -55, RZ + 84))]
    audit(items, S, -60, 17)
    print("saved", draw("0306-1", "气象杆与传感器三件套", items, S,
                        note="从可开启的天窗边伸出屋面，离屋脊 1m 以上；百叶结构让空气流通又挡住太阳直晒，否则温度会虚高",
                        sig="设想 · 0306", az=-60, el=17, fov=27))


