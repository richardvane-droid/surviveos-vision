def fig2():
    S = []
    # 阁楼间东侧隔断（背景件，只给够用的一块）
    S.append(ghost(box((620, 60, 760), (-180, 0, -120), "东侧隔断")))

    # 隔断上的挂条（法式挂条，斜面朝上）
    S.append(prism([(0, 0), (20, 0), (20, 34), (0, 56)], 300, "x", (-20, -22, 300), "墙挂条"))

    EY = 0.0
    def Y(k):                                     # 各层沿 -Y 依次爆炸
        return -140 - k * 235.0

    # 背板 + 背面挂条
    S.append(box((300, 18, 230), (-20, Y(0), 90), "木框背板"))
    S.append(prism([(0, 0), (20, 0), (0, 56)], 260, "x", (0, Y(0) - 20, 250), "背板挂条"))

    # ③ 18650 电池 + 电池座
    S.append(box((120, 34, 46), (-215, Y(1), 150), "18650 电池座"))
    S.append(cyl(20, 74, "x", (-212, Y(1) + 17, 173), 14, "18650 电池"))
    S.append(box((28, 22, 22), (-90, Y(1) + 6, 162), "电源开关"))
    S.append(path_tube([(-95, Y(1) + 17, 173), (40, Y(1) - 60, 170)], 5, 6, "电池线"))

    # ② ESP32 驱动板
    S.append(box((250, 14, 150), (-5, Y(2), 130), "ESP32 驱动板"))
    S.append(box((60, 16, 26), (20, Y(2) - 16, 200), "ESP32 模块"))
    S.append(box((90, 14, 20), (120, Y(2) - 14, 160), "屏排线座"))
    for i in range(4):
        S.append(box((10, 10, 10), (200, Y(2) - 10, 150 + i * 16), "接口"))

    # ① 7.5 寸墨水屏 800×480（170×111mm 显示区）
    PX0, PZ0 = -15.0, 110.0
    S.append(box((250, 12, 175), (PX0, Y(3), PZ0), "7.5 寸墨水屏"))
    S.append(box((178, 6, 119), (PX0 + 36, Y(3) - 6, PZ0 + 28), "显示区"))
    # ⑤ 屏上内容：当前值 + 24 小时曲线 + 预警行
    for i in range(2):
        S.append(box((62, 4, 9), (PX0 + 44, Y(3) - 10, PZ0 + 128 - i * 16), "当前值"))
    cur = []
    for i in range(13):
        t = i / 12
        zz = PZ0 + 62 + 26 * math.sin(t * 5.0) * (0.4 + 0.6 * t)
        cur.append((PX0 + 44 + 160 * t, Y(3) - 10, zz))
    S.append(path_tube(cur, 3.0, 6, "24 小时曲线"))
    S.append(box((160, 4, 3), (PX0 + 44, Y(3) - 10, PZ0 + 40), "曲线基线"))
    S.append(box((150, 4, 8), (PX0 + 48, Y(3) - 10, PZ0 + 34), "预警行"))

    # ④ 木框（最外一层，正面没有按键）
    FY = Y(4)
    fr = [box((360, 40, 40), (-70, FY, PZ0 - 63)), box((360, 40, 40), (-70, FY, PZ0 + 197)),
          box((40, 40, 300), (-70, FY, PZ0 - 63)), box((40, 40, 300), (250, FY, PZ0 - 63))]
    S.append(merge(fr, "木框"))

    items = [("①", "7.5 寸 800×480 墨水屏", (PX0 + 125, Y(3) - 6, PZ0 + 90)),
             ("②", "ESP32 驱动板，每 10 分钟刷新一次", (215, Y(2) - 2, 235)),
             ("③", "一节 18650，静态不耗电能撑几个月", (-155, Y(1), 173)),
             ("④", "木框壁挂，正面没有按键", (110, FY, PZ0 + 217)),
             ("⑤", "当前值 + 24 小时曲线 + 预警行", (PX0 + 124, Y(3) - 10, PZ0 + 70))]
    audit(items, S, -64, 16)
    print("saved", draw("0306-2", "墨水屏天气面板", items, S,
                        note="挂在阁楼间东侧与木工间的隔断上、天窗正东；数据从 HomeAssistant 模板实体拉取",
                        sig="设想 · 0306", az=-64, el=16, fov=27))


fig1()
fig2()
