def corrugated(pts, r=18, rings=9, name="波纹管"):
    """波纹穿线管：一根折线管 + 几道环箍。"""
    o = [path_tube(pts, r * 0.8, 7, name)]
    for i in range(rings):
        t = (i + 0.5) / rings
        p0 = np.asarray(pts[0], float)
        p1 = np.asarray(pts[-1], float)
        p = p0 + (p1 - p0) * t
        o.append(cyl(r, 16, "z", (p[0], p[1], p[2]), 8, name))
    return merge(o, name)


