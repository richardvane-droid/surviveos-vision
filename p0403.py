    audit(items, S, -58, 20)
    print("saved", draw("0403-2", "直排风管组", items, S,
                        note="每个弯头都会吃掉一截风量，漆雾在弯头处最容易积垢，所以选一根直管；柜位离台锯 5m 以上",
                        sig="设想 · 0403", az=-58, el=20, fov=27))


