RL = 1000                      # 三根麻绳横拉 1m
ZR = (1720, 2020, 2320)        # 三根绳的高度（底边 1500、顶边贴梁底 2400）


# ---------------------------------------------------------------- 0104-1
def fig1():
    YH, YR, YC, YP, YL = -30, -270, -520, -790, -430
    S = [wall(1760, 1120, 80, (-620, 0, 1420))]

    # ② 铜钩：两端各三只，拧进北墙
    for z in ZR:
        for x in (-70, RL + 70):
            S += [cyl(7, 78, "y", (x, YH - 78, z), 10, "铜钩"),
                  cyl(7, 52, "z", (x, YH - 74, z), 10, "铜钩"),
                  cyl(13, 12, "y", (x, YH - 12, z), 12, "钩座")]

    # ③ 三根 5mm 麻绳，中点下垂 30
    for z in ZR:
        S.append(rope((-70, YR, z), (RL + 70, YR, z), sag=30, r=5, n=13, name="5mm 麻绳"))

    # ④ 3cm 原木小夹子，每根约 8 只
    for z in ZR:
        cl = []
        for i in range(8):
            x = 88 + i * 118
            t = (x) / RL
            zz = z - 4 * 30 * t * (1 - t)
            cl += [box((13, 32, 30), (x, YC - 16, zz - 16), "木夹"),
                   box((13, 32, 30), (x + 17, YC - 16, zz - 16), "木夹"),
                   cyl(5, 34, "x", (x, YC, zz + 4), 8, "夹簧")]
        S.append(merge(cl, "3cm 原木小夹子"))

    # ⑤ 4×6 富士相纸，不塑封
    for z in ZR:
        ph = []
        for i in range(8):
            x = 88 + i * 118
            t = x / RL
            zz = z - 4 * 30 * t * (1 - t)
            ph.append(box((102, 2, 152), (x - 42, YP, zz - 168), "4×6 照片"))
        S.append(merge(ph, "4×6 富士相纸"))

    # ① 2400K 灯带，斜上方打
    ld = [box((RL + 60, 40, 22), (-30, YL, 2430), "2400K 灯带"),
          box((RL + 60, 46, 26), (-30, YL - 6, 2452), "灯槽")]
    S.append(rot(merge(ld, "2400K 灯带"), 28, "x", (RL / 2, YL, 2450)))

    items = [("①", "2400K 灯带斜上方打，避开咖啡机蒸汽", (620, YL, 2452)),
             ("②", "铜钩拧进北墙，要吃住 1m 拉力", (RL + 70, YH - 66, 2020)),
             ("③", "三根 5mm 麻绳，中点故意下垂 3cm", (RL + 40, YR, ZR[1] - 3)),
             ("④", "3cm 原木小夹子，本色，每根约 8 只", (566, YC - 16, ZR[2] - 4 * 30 * 0.56 * 0.44)),
             ("⑤", "4×6 富士相纸暖调冲印，不塑封", (330, YP, ZR[0] - 100))]
    audit(items, S, -52, 16)
    p = draw("0104-1", "麻绳木夹挂片系统", items, S,
             note="夹在 0103 画框墙和 0102 九宫格之间约 1m 宽；成本几乎为零，但每个细节都有讲究",
             sig="设想 · 0104", az=-52, el=16, fov=27)
    print("saved", p)


