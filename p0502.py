LEAF = [(0, -1.0), (0.85, -0.3), (1.25, 0.55), (0.45, 1.1), (0, 0.72),
        (-0.45, 1.1), (-1.25, 0.55), (-0.85, -0.3)]      # 爬山虎叶的五裂轮廓


def ivy(pos, n=4, r=95, name="爬山虎叶"):
    """一簇贴墙的爬山虎叶：n 片五裂薄叶，错开叠在墙面上。"""
    o = []
    for i in range(n):
        a = i * 2.35 + 0.6
        s = r * (0.72 + 0.17 * (i % 3))
        sec = [(u * s, v * s) for u, v in LEAF]
        o.append(prism(sec, 7, "y", (pos[0] + math.cos(a) * r * 0.85,
                                     pos[1] - 8 - i * 7,
                                     pos[2] + math.sin(a) * r * 0.85), name))
    return merge(o, name)


