def fig2():
    """放大到灯具尺度：墙脚一小段 + 切开的种植带 + 埋地灯爆炸。"""
    S = []
    S.append(wall(1100, 950, 140, (-520, 0, 0), "x", "砖墙"))

    # 切开 40cm 种植带：左右两块原土，中间留缺口露出套筒埋深
    S.append(cut_soil(360, 400, 460, (-520, -400, -460), "原土"))
    S.append(cut_soil(620, 400, 460, (160, -400, -460), "原土"))
    S.append(cut_soil(320, 150, 460, (-160, -150, -460), "原土"))

    # ② 预埋 PVC 套筒 φ10cm、底部排水孔 + 套筒底碎石
    SX, SY = 0.0, -250.0
    S.append(cyl(58, 400, "z", (SX, SY, -440), 18, "PVC 预埋套筒"))
    S.append(cyl(50, 14, "z", (SX, SY, -440), 16, "套筒底"))
    for i in range(3):
        a = i * 2.1 - 1.2
        S.append(cyl(9, 26, "x", (SX + 52 * math.cos(a) - 13, SY + 52 * math.sin(a), -398), 8, "排水孔"))
    S.append(gravel((SX - 44, SY - 44, -426), 88, 88, 7, 16, 13, "套筒底碎石"))

    # ①③ 灯具沿 +Z 往右前方爆炸，避开左半边的藤叶
    def P(z):
        return (SX + (z - 40) * 0.42, SY - (z - 40) * 0.16)
    x3, y3 = P(190)
    S.append(merge([cyl(74, 22, "z", (x3, y3, 190), 20, "压环面盖"),
                    cyl(46, 14, "z", (x3, y3, 176), 18, "面盖内圈")], "压环面盖"))
    x2, y2 = P(380)
    S.append(cyl(64, 14, "z", (x2, y2, 380), 20, "防水胶圈"))
    x1, y1 = P(610)
    S.append(merge([cyl(52, 100, "z", (x1, y1, 610), 20, "IP67 埋地灯"),
                    cyl(41, 18, "z", (x1, y1, 710), 18, "灯珠腔"),
                    cyl(34, 10, "z", (x1, y1, 728), 16, "3000K COB")], "IP67 埋地灯"))

    # ④ 30° 光束朝上斜 15° 打叶背；墙上一片透光的爬山虎叶
    for dx in (20.0, -290.0):
        S.append(seg_tube((SX - 16, SY + 30, 20), (SX + dx, SY + 230, 900), 5, 5, "30° 光束边界"))
    for (x, z) in ((-400.0, 330.0), (-170.0, 520.0), (-330.0, 720.0), (-30.0, 780.0)):
        S.append(ivy((x, -70, z), 4, 92, "爬山虎叶"))
    S.append(vine((-280, -74, 0), (-210, -74, 920), 7, 100, 13, "藤蔓"))

    # ⑤ 24V 供电线：从套筒穿出，走地下到墙角穿墙
    S.append(path_tube([(SX + 34, SY, -380), (560, SY, -380), (560, -105, -380),
                        (560, -105, -60)], 15, 7, "24V 供电线"))
    S.append(cyl(28, 150, "z", (560, -105, -60), 12, "穿墙管"))

    items = [("①", "3000K 暖光 IP67 埋地灯，3W×2", (x1 + 52, y1, 666)),
             ("②", "预埋 PVC 套筒 φ10cm，底留排水孔", (SX + 58, SY, -270)),
             ("③", "防水胶圈 + 压环面盖，与地面齐平", (x3 + 74, y3, 200)),
             ("④", "光束角 30°，朝上斜 15° 打叶背", (SX - 250, SY + 190, 790)),
             ("⑤", "24V 供电，HA 日落亮、23:00 灭", (560, -105, 40))]
    audit(items, S, -64, 15)
    print("saved", draw("0502-2", "透光地灯组", items, S,
                        note="埋在 40cm 种植带里，套筒底留排水孔，杭州暴雨泡不坏；两盏间距 2.5m，每盏 3W，太亮反而一片白",
                        sig="设想 · 0502", az=-64, el=15, fov=27))


