def fig1():
    """取南墙东段约 2.8m：种植带剖面 + 引蔓横杆 + 观察窗。"""
    S = []
    S.append(wall(2800, 2560, 140, (-400, 0, 0), "x", "木屋南墙"))
    # 西边就是南门框：种植带在门口断开，槽的西端敞着口露出断面
    S.append(box((95, 75, 2050), (-400, -75, 0), "南门框"))

    # ① 种植带土槽 40cm 宽 40cm 深（前壁 + 槽底，西端敞口露断面）
    TX0, TX1 = -300.0, 2400.0
    S.append(box((TX1 - TX0, 400, 70), (TX0, -400, -400), "种植带槽底"))
    S.append(box((TX1 - TX0, 45, 400), (TX0, -400, -400), "槽前壁"))
    # 原位回填：底 5cm 陶粒 + 腐叶土
    S.append(box((TX1 - TX0, 310, 50), (TX0, -355, -330), "陶粒排水层"))
    S.append(box((TX1 - TX0, 310, 245), (TX0, -355, -280), "腐叶土回填"))

    # ② 取一截回填层爆炸到东侧空处：5cm 陶粒 + 腐叶土
    CX, CY, CW = 2680.0, -1250.0, 780.0
    S.append(box((CW, 310, 50), (CX, CY, 120), "5cm 陶粒排水层"))
    for i in range(6):
        S.append(cyl(24, 20, "z", (CX + 70 + i * 128, CY + 155, 168), 7, "陶粒"))
    S.append(box((CW, 310, 245), (CX, CY, 520), "腐叶土回填"))

    # ③ 三叶地锦每 80cm 一株，第一年爬到 1.5m
    for i, x in enumerate((60.0, 860.0, 1660.0)):
        S.append(seedling((x, -190, -35), 300, "三叶地锦"))
        top = 1560.0 if i != 1 else 2180.0
        S.append(vine((x, -76, 120), (x + 90, -76, top), 7, 105, 15, "藤蔓"))
        for k in range(3):
            S.append(ivy((x + 40 + (k - 1) * 150, -76, 430 + k * (top - 560) / 3), 4, 92, "爬山虎叶"))

    # ④ 毛竹横杆 3m，角铁托架固定在 2.2m 高
    PZ = 2200.0
    S.append(cyl(45, 3000, "x", (-330, -170, PZ), 14, "毛竹横杆"))
    for x in (-60.0, 1060.0, 2180.0):
        S.append(box((60, 210, 14), (x, -210, PZ - 52), "角铁托架"))
        S.append(box((60, 14, 130), (x, -70, PZ - 52), "角铁托架"))
    for x in (300.0, 1350.0, 1950.0):
        S.append(ivy((x, -180, PZ - 40), 4, 96, "爬山虎叶"))

    # ⑤ 60×60cm 观察窗：薄铁皮框隔离，看砖墙和藤须的对比
    OX, OZ = 1180.0, 1120.0
    ow = []
    for dz in (0.0, 560.0):
        ow.append(box((640, 75, 42), (OX, -75, OZ + dz), "观察窗铁皮框"))
    for dx in (0.0, 598.0):
        ow.append(box((42, 75, 602), (OX + dx, -75, OZ), "观察窗铁皮框"))
    S.append(merge(ow, "观察窗铁皮框"))

    items = [("①", "种植带 ≈4m×0.4m，门口断开", (TX0, -200, -200)),
             ("②", "底铺 5cm 陶粒，上填腐叶土", (CX + 390, CY, 620)),
             ("③", "三叶地锦每 80cm 一株", (860, -190, 170)),
             ("④", "毛竹横杆 3m，角铁托架挑在 2.2m", (1060, -215, PZ)),
             ("⑤", "60×60cm 观察窗，铁皮框隔离", (OX + 320, -75, OZ + 580))]
    audit(items, S, -108, 15)
    print("saved", draw("0502-1", "种植带与引蔓横杆", items, S,
                        note="木屋南墙 ≈5.1m 宽的砖墙外立面，门窗框外 20cm 剪干净；藤最高引到 2.2m 的横杆，不上阁楼屋面",
                        sig="设想 · 0502", az=-108, el=15, fov=27))


